"""Losslessly package browser JPEG pixels as PNGs; never retouch app content."""

import hashlib
import json
import sys
from pathlib import Path

from PIL import Image

project = Path(__file__).resolve().parent.parent
staging = Path(sys.argv[1])
output = project / "public/captures"
output.mkdir(parents=True, exist_ok=True)
log = json.loads((staging / "capture-log.json").read_text())
keys = sorted({entry["key"] for entry in log})
assert len(keys) == 12
manifest = []
pages = {}
for locale in ("en", "zh-CN"):
    for key in keys:
        entry = next(
            item for item in log if item["locale"] == locale and item["key"] == key
        )
        for suffix in ("", "-page"):
            source = staging / f"{locale}-{key}{suffix}.jpg"
            if not source.exists() and suffix:
                continue
            with Image.open(source) as image:
                assert image.width == 1440, source
                if not suffix:
                    assert image.height == 900, (source, image.size)
                destination = output / f"{locale}-{key}{suffix}.png"
                image.save(destination, format="PNG", optimize=True)
                manifest.append(
                    {
                        **entry,
                        "file": destination.name,
                        "width": image.width,
                        "height": image.height,
                        "fullPage": bool(suffix),
                        "captureOriginY": 0 if suffix else entry["captureOriginY"],
                        "originalJpegSha256": hashlib.sha256(
                            source.read_bytes()
                        ).hexdigest(),
                        "sha256": hashlib.sha256(destination.read_bytes()).hexdigest(),
                    }
                )
                pages[f"{locale}-{key}"] = {
                    "imageKey": key + suffix,
                    "height": image.height,
                }
(output / "manifest.json").write_text(
    json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
)
(project / "src/captured-pages.ts").write_text(
    "// Generated by scripts/prepare-captures.py from real browser captures.\n"
    + "export const capturedPages: Record<string, { imageKey: string; height: number }> = "
    + json.dumps(pages, indent=2)
    + ";\n"
)
print(
    f"Packaged {len(manifest)} authentic captures, {len(pages)} localized workflow states."
)
