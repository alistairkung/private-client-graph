"""Generate checked TypeScript consumers from the versioned Pydantic read contracts."""
import argparse
from pathlib import Path
from typing import Any

from .contracts import Comparison, ExperimentDetail, HistoryPage


def _type(schema: dict[str, Any]) -> str:
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'anyOf' in schema:
        return ' | '.join(_type(item) for item in schema['anyOf'])
    if 'const' in schema:
        import json
        return json.dumps(schema['const'])
    if 'enum' in schema:
        import json
        return ' | '.join(json.dumps(item) for item in schema['enum'])
    kind = schema.get('type')
    if kind == 'array':
        if 'prefixItems' in schema:
            return '[' + ', '.join(_type(item) for item in schema['prefixItems']) + ']'
        return f'Array<{_type(schema.get("items", {}))}>'
    if kind == 'object':
        if 'properties' in schema:
            return '{\n' + ''.join(f'  {key}: {_type(value)};\n'
                for key, value in schema['properties'].items()) + '}'
        additional = schema.get('additionalProperties', {})
        return f'Record<string, {_type(additional) if isinstance(additional, dict) else "unknown"}>'
    return {'string': 'string', 'integer': 'number', 'number': 'number',
            'boolean': 'boolean', 'null': 'null'}.get(str(kind), 'unknown')


def render() -> str:
    definitions = {}
    for model in (HistoryPage, ExperimentDetail, Comparison):
        schema = model.model_json_schema(mode='serialization')
        definitions.update(schema.pop('$defs', {}))
        definitions[model.__name__] = schema
    return '// Generated by python -m private_client_graph.workbench.typescript. Do not edit.\n' + '\n'.join(
        f'export type {name} = {_type(schema)};\n' for name, schema in sorted(definitions.items()))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path('web/research/shared/contracts.ts')
    if args.check:
        if path.read_text() != render():
            raise SystemExit('Research TypeScript contracts are stale; regenerate them.')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render())


if __name__ == '__main__':
    main()
